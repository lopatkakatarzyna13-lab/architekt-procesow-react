// A separate browser context uses only fictional data; no external API calls.
import assert from 'node:assert/strict'
import { execFileSync } from 'node:child_process'
import { readFile } from 'node:fs/promises'
import { chromium } from 'playwright'
import { BpmnModdle } from 'bpmn-moddle'

const browser = await chromium.launch({ headless: true, ...(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {}) })
try {
  const page = await browser.newPage({ viewport: { width: 1366, height: 900 }, acceptDownloads: true })
  await page.goto('http://127.0.0.1:5173/')
  await page.getByRole('button', { name: /Dodaj kroki samodzielnie/ }).click()
  await page.getByLabel(/Nazwa procesu/).fill('Fikcyjny proces HR')
  await page.getByLabel(/Cel procesu/).fill('Sprawdzenie danych')
  await page.getByLabel(/Co rozpoczyna proces/).fill('Zgłoszenie')
  await page.getByLabel(/Co kończy proces/).fill('Potwierdzenie')
  await page.getByRole('button', { name: /Zapisz zakres i przejdź dalej/ }).click()
  await page.getByLabel(/Nazwa kroku/).fill('Weryfikacja danych')
  await page.getByRole('button', { name: 'Dodaj krok' }).click()
  await page.getByLabel(/Nazwa kroku/).fill('Wysłanie dokumentów')
  await page.getByRole('button', { name: 'Dodaj krok' }).click()
  const button = page.getByRole('button', { name: 'Pobierz BPMN 2.0' })
  assert.equal(await button.isDisabled(), true, 'unsaved process must not be exported')
  await page.getByRole('button', { name: 'Zapisz proces AS-IS' }).click()
  await page.getByRole('button', { name: 'Pokaż podgląd BPMN' }).click()
  const preview = page.getByRole('img', { name: 'Podgląd zapisanego diagramu BPMN AS-IS' })
  await preview.locator('[data-element-id="StartEvent_1"]').waitFor({ state: 'visible' })
  await preview.locator('[data-element-id="Task_1"]').waitFor({ state: 'visible' })
  await preview.locator('[data-element-id="EndEvent_1"]').waitFor({ state: 'visible' })
  assert.equal(await preview.locator('.bjs-powered-by').isVisible(), true)
  await page.getByRole('button', { name: 'Powiększ BPMN' }).click()
  await page.getByRole('button', { name: 'Dopasuj BPMN' }).click()
  const [download] = await Promise.all([page.waitForEvent('download'), button.click()])
  assert.equal(download.suggestedFilename(), 'proces-asis.bpmn')
  const path = await download.path()
  const xml = await readFile(path, 'utf8')
  const { rootElement, warnings } = await new BpmnModdle().fromXML(xml)
  assert.deepEqual(warnings, [])
  const process = rootElement.rootElements[0]
  assert.equal(process.name, 'Fikcyjny proces HR')
  assert.deepEqual(process.flowElements.filter((element) => element.$type === 'bpmn:Task').map((element) => element.name), ['Weryfikacja danych', 'Wysłanie dokumentów'])
  assert.equal(rootElement.diagrams[0].plane.planeElement.length, 7)
  execFileSync('java', ['tests/ValidateBpmnXsd.java', 'node_modules/bpmn-moddle/resources/bpmn/xsd/BPMN20.xsd', path], { stdio: 'inherit' })
  await page.getByLabel('Tor BPMN — krok 1: Weryfikacja danych').fill('HR')
  assert.equal(await button.isDisabled(), true, 'an unsaved lane draft must disable the export')
  await page.getByRole('button', { name: 'Zapisz tor — krok 1: Weryfikacja danych' }).click()
  await page.getByRole('button', { name: 'Zapisz proces AS-IS' }).click()
  assert.equal(await button.isDisabled(), true, 'partial lane assignment must block the export')
  await page.getByLabel('Tor BPMN — krok 2: Wysłanie dokumentów').fill('Biuro')
  await page.getByRole('button', { name: 'Zapisz tor — krok 2: Wysłanie dokumentów' }).click()
  await page.getByRole('button', { name: 'Zapisz proces AS-IS' }).click()
  const [laneDownload] = await Promise.all([page.waitForEvent('download'), button.click()])
  const lanePath = await laneDownload.path()
  const laneModel = await new BpmnModdle().fromXML(await readFile(lanePath, 'utf8'))
  assert.deepEqual(laneModel.warnings, [])
  assert.deepEqual(laneModel.rootElement.rootElements[0].laneSets[0].lanes.map((lane) => lane.name), ['HR', 'Biuro'])
  execFileSync('java', ['tests/ValidateBpmnXsd.java', 'node_modules/bpmn-moddle/resources/bpmn/xsd/BPMN20.xsd', lanePath], { stdio: 'inherit' })
  await page.getByLabel('Od kroku').selectOption({ label: '2. Wysłanie dokumentów' })
  await page.getByLabel('Do kroku').selectOption({ label: '1. Weryfikacja danych' })
  await page.getByLabel('Kiedy następuje przejście?').fill('Brak danych')
  await page.getByRole('button', { name: 'Dodaj połączenie' }).click()
  assert.equal(await preview.count(), 0, 'a preview of the prior version must disappear when process changes')
  await page.getByRole('button', { name: 'Zapisz proces AS-IS' }).click()
  assert.equal(await button.isDisabled(), true, 'an alternative path must block BPMN export')
  await page.getByText(/Uzupełnij decyzję BPMN dla kroku/).waitFor()
  await page.getByLabel('Pytanie decyzji — Wysłanie dokumentów').fill('Dane kompletne?')
  await page.getByLabel('Kiedy kontynuować podstawową ścieżkę — Wysłanie dokumentów').fill('Kompletne')
  await page.getByRole('button', { name: 'Zapisz decyzję BPMN — Wysłanie dokumentów' }).click()
  assert.equal(await button.isDisabled(), true, 'the decision must be saved in the process first')
  await page.getByLabel('Krok w Twoim procesie').selectOption({ label: '1. Weryfikacja danych' })
  await page.getByLabel('Nazwa basenu Twojego procesu').fill('Firma')
  await page.getByLabel('Nazwa basenu zewnętrznego').fill('Biuro rachunkowe')
  await page.getByLabel('Kierunek wiadomości').selectOption('outgoing')
  await page.getByLabel('Co jest przekazywane?').fill('Dane pracownika')
  await page.getByRole('button', { name: 'Dodaj wiadomość BPMN' }).click()
  await page.getByLabel('Krok w Twoim procesie').selectOption({ label: '2. Wysłanie dokumentów' })
  await page.getByLabel('Nazwa basenu Twojego procesu').fill('Firma')
  await page.getByLabel('Nazwa basenu zewnętrznego').fill('Biuro rachunkowe')
  await page.getByLabel('Kierunek wiadomości').selectOption('incoming')
  await page.getByLabel('Co jest przekazywane?').fill('Dokumenty')
  await page.getByRole('button', { name: 'Dodaj wiadomość BPMN' }).click()
  await page.getByRole('button', { name: 'Zapisz proces AS-IS' }).click()
  const [branchedDownload] = await Promise.all([page.waitForEvent('download'), button.click()])
  const branchedPath = await branchedDownload.path()
  const branched = await new BpmnModdle().fromXML(await readFile(branchedPath, 'utf8'))
  assert.deepEqual(branched.warnings, [])
  const elements = branched.rootElement.rootElements[0].flowElements
  const decision = elements.find((element) => element.$type === 'bpmn:ExclusiveGateway' && element.gatewayDirection === 'Diverging')
  const merge = elements.find((element) => element.$type === 'bpmn:ExclusiveGateway' && element.gatewayDirection === 'Converging')
  assert.equal(decision.name, 'Dane kompletne?')
  assert.deepEqual(decision.outgoing.map((flow) => flow.name).sort(), ['Brak danych', 'Kompletne'])
  assert.equal(merge.incoming.length, 2)
  const lanes = branched.rootElement.rootElements[0].laneSets[0].lanes
  assert.deepEqual(lanes.map((lane) => lane.name), ['HR', 'Biuro'])
  const collaboration = branched.rootElement.rootElements.find((item) => item.$type === 'bpmn:Collaboration')
  assert.deepEqual(collaboration.participants.map((item) => item.name), ['Firma', 'Biuro rachunkowe'])
  assert.deepEqual(collaboration.messageFlows.map((item) => [item.name, item.sourceRef.id, item.targetRef.id]), [
    ['Dane pracownika', 'Task_1', 'Participant_External_1'], ['Dokumenty', 'Participant_External_1', 'Task_2'],
  ])
  assert.equal(branched.rootElement.diagrams[0].plane.bpmnElement.id, collaboration.id)
  assert.ok(lanes[0].flowNodeRef.some((node) => node.id === merge.id))
  assert.ok(lanes[1].flowNodeRef.some((node) => node.id === decision.id))
  execFileSync('java', ['tests/ValidateBpmnXsd.java', 'node_modules/bpmn-moddle/resources/bpmn/xsd/BPMN20.xsd', branchedPath], { stdio: 'inherit' })
  await page.getByRole('button', { name: 'Pokaż podgląd BPMN' }).click()
  await preview.locator(`[data-element-id="${decision.id}"]`).waitFor({ state: 'visible' })
  await preview.locator(`[data-element-id="${merge.id}"]`).waitFor({ state: 'visible' })
  for (const lane of lanes) await preview.locator(`[data-element-id="${lane.id}"]`).waitFor({ state: 'visible' })
  for (const participant of collaboration.participants) await preview.locator(`[data-element-id="${participant.id}"]`).waitFor({ state: 'visible' })
  for (const flow of collaboration.messageFlows) await preview.locator(`[data-element-id="${flow.id}"] .djs-visual > path`).first().waitFor({ state: 'attached' })
  for (const flow of decision.outgoing) {
    // A horizontal SVG path has a zero-height bounding box, which Playwright
    // may classify as hidden even when its stroke is drawn. Inspect the line.
    const line = preview.locator(`[data-element-id="${flow.id}"] .djs-visual > path`).first()
    await line.waitFor({ state: 'attached' })
    const geometry = await line.evaluate((element) => {
      const rect = element.getBoundingClientRect()
      const style = getComputedStyle(element)
      return { length: element.getTotalLength(), width: rect.width, height: rect.height, stroke: style.stroke, display: style.display, visibility: style.visibility }
    })
    console.log('BPMN_FLOW_GEOMETRY', JSON.stringify({ id: flow.id, ...geometry }))
    assert.ok(geometry.length > 0 && (geometry.width > 0 || geometry.height > 0), 'flow path must have measurable geometry')
    assert.notEqual(geometry.stroke, 'none', 'flow path must have a visible stroke')
    assert.notEqual(geometry.display, 'none')
    assert.notEqual(geometry.visibility, 'hidden')
  }
  assert.equal(await preview.locator('.bjs-powered-by').isVisible(), true)
  if (globalThis.process.env.BPMN_SCREENSHOT_PATH) await preview.screenshot({ path: globalThis.process.env.BPMN_SCREENSHOT_PATH })
  await page.getByLabel('Nazwa działania').fill('Sprawdzenie danych')
  await page.getByRole('button', { name: 'Dodaj działanie zewnętrzne' }).click()
  await page.getByLabel('Nazwa działania').fill('Przygotowanie dokumentów')
  await page.getByRole('button', { name: 'Dodaj działanie zewnętrzne' }).click()
  await page.getByLabel('Krok w Twoim procesie').selectOption({ label: '1. Weryfikacja danych' })
  await page.getByLabel('Nazwa basenu Twojego procesu').fill('Firma')
  await page.getByLabel('Nazwa basenu zewnętrznego').fill('Biuro rachunkowe')
  await page.getByLabel('Kierunek wiadomości').selectOption('outgoing')
  await page.getByLabel('Działanie uczestnika zewnętrznego (opcjonalnie)').selectOption({ label: 'Sprawdzenie danych' })
  await page.getByLabel('Co jest przekazywane?').fill('Formularz')
  await page.getByRole('button', { name: 'Dodaj wiadomość BPMN' }).click()
  await page.getByLabel('Krok w Twoim procesie').selectOption({ label: '2. Wysłanie dokumentów' })
  await page.getByLabel('Nazwa basenu Twojego procesu').fill('Firma')
  await page.getByLabel('Nazwa basenu zewnętrznego').fill('Biuro rachunkowe')
  await page.getByLabel('Kierunek wiadomości').selectOption('incoming')
  await page.getByLabel('Działanie uczestnika zewnętrznego (opcjonalnie)').selectOption({ label: 'Przygotowanie dokumentów' })
  await page.getByLabel('Co jest przekazywane?').fill('Potwierdzenie')
  await page.getByRole('button', { name: 'Dodaj wiadomość BPMN' }).click()
  await page.getByRole('button', { name: 'Zapisz proces AS-IS' }).click()
  const [externalDownload] = await Promise.all([page.waitForEvent('download'), button.click()])
  const externalPath = await externalDownload.path()
  const externalModel = await new BpmnModdle().fromXML(await readFile(externalPath, 'utf8'))
  assert.deepEqual(externalModel.warnings, [])
  const externalCollaboration = externalModel.rootElement.rootElements.find((item) => item.$type === 'bpmn:Collaboration')
  assert.deepEqual(externalCollaboration.participants[1].processRef.flowElements.filter((item) => item.$type === 'bpmn:Task').map((item) => item.name), ['Sprawdzenie danych', 'Przygotowanie dokumentów'])
  assert.deepEqual(externalCollaboration.messageFlows.filter((item) => ['Formularz', 'Potwierdzenie'].includes(item.name)).map((item) => [item.sourceRef.id, item.targetRef.id]), [['Task_1', 'ExternalTask_1'], ['ExternalTask_2', 'Task_2']])
  execFileSync('java', ['tests/ValidateBpmnXsd.java', 'node_modules/bpmn-moddle/resources/bpmn/xsd/BPMN20.xsd', externalPath], { stdio: 'inherit' })
  await page.getByRole('button', { name: 'Pokaż podgląd BPMN' }).click()
  await preview.locator('[data-element-id="ExternalTask_1"]').waitFor({ state: 'visible' })
  await preview.locator('[data-element-id="ExternalTask_2"]').waitFor({ state: 'visible' })
  if (globalThis.process.env.BPMN_SCREENSHOT_PATH) await preview.screenshot({ path: globalThis.process.env.BPMN_SCREENSHOT_PATH })
  // Additional long, explicitly named transfers exercise dense diagrams without real data.
  const longLabels = [
    'Dane pracownika i dokumenty niezbędne do przygotowania umowy',
    'Potwierdzenie danych i prośba o uzupełnienie brakujących informacji',
    'Informacja o zmianie warunków zatrudnienia i planowanej dacie rozpoczęcia pracy',
    'Projekt dokumentów pracowniczych do weryfikacji przez przedstawiciela firmy',
  ]
  for (const [index, label] of longLabels.entries()) {
    await page.getByLabel('Krok w Twoim procesie').selectOption({ label: index % 2 ? '2. Wysłanie dokumentów' : '1. Weryfikacja danych' })
    await page.getByLabel('Nazwa basenu Twojego procesu').fill('Firma')
    await page.getByLabel('Nazwa basenu zewnętrznego').fill('Biuro rachunkowe')
    await page.getByLabel('Kierunek wiadomości').selectOption(index % 2 ? 'incoming' : 'outgoing')
    await page.getByLabel('Działanie uczestnika zewnętrznego (opcjonalnie)').selectOption({ label: index % 2 ? 'Przygotowanie dokumentów' : 'Sprawdzenie danych' })
    await page.getByLabel('Co jest przekazywane?').fill(label)
    await page.getByRole('button', { name: 'Dodaj wiadomość BPMN' }).click()
  }
  await page.getByRole('button', { name: 'Zapisz proces AS-IS' }).click()
  const [denseDownload] = await Promise.all([page.waitForEvent('download'), button.click()])
  const densePath = await denseDownload.path()
  const dense = await new BpmnModdle().fromXML(await readFile(densePath, 'utf8'))
  assert.deepEqual(dense.warnings, [])
  const denseCollaboration = dense.rootElement.rootElements.find((item) => item.$type === 'bpmn:Collaboration')
  assert.equal(denseCollaboration.messageFlows.length, 8)
  for (const label of longLabels) assert.ok(denseCollaboration.messageFlows.some((flow) => flow.name === label))
  execFileSync('java', ['tests/ValidateBpmnXsd.java', 'node_modules/bpmn-moddle/resources/bpmn/xsd/BPMN20.xsd', densePath], { stdio: 'inherit' })
  await page.getByRole('button', { name: 'Pokaż podgląd BPMN' }).click()
  await preview.locator('[data-element-id="MessageFlow_8"]').first().waitFor({ state: 'attached' })
  if (globalThis.process.env.BPMN_SCREENSHOT_PATH) await preview.screenshot({ path: globalThis.process.env.BPMN_SCREENSHOT_PATH })
  await page.getByLabel('Pytanie decyzji — Wysłanie dokumentów').fill('Zmienione pytanie?')
  assert.equal(await preview.count(), 0, 'unsaved decision changes must hide the old preview')
  console.log('PASS: BPMN pools, message flows, lanes and decision download, XSD, rendering and safe preview invalidation')
} finally {
  await browser.close()
}
