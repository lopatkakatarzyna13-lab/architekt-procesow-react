// @vitest-environment jsdom
import { afterEach, beforeEach, expect, it, vi } from 'vitest'
import { cleanup, render, screen, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import App from './App'

// Chromium verifies SVG rendering and image decoding in the PDF scenario.
vi.mock('./createPrintBpmn', () => ({
  createPrintBpmn: async () => 'data:image/svg+xml,%3Csvg%20xmlns%3D%22http%3A%2F%2Fwww.w3.org%2F2000%2Fsvg%22%2F%3E',
}))

beforeEach(() => { localStorage.clear(); sessionStorage.clear(); vi.spyOn(window, 'scrollTo').mockImplementation(() => {}); vi.stubGlobal('ResizeObserver', class { observe() {} unobserve() {} disconnect() {} }) })
afterEach(() => { cleanup(); vi.restoreAllMocks(); vi.unstubAllGlobals() })

it('takes a fictional workshop from proposal through reopen, report and printing', async () => {
  const user = userEvent.setup()
  const transcript = 'HR sprawdza kompletność danych. Następnie biuro przygotowuje dokumenty.'
  const steps = ['Sprawdzenie kompletności danych', 'Przygotowanie dokumentów']
  const confirm = vi.spyOn(window, 'confirm').mockReturnValue(true)
  const print = vi.spyOn(window, 'print').mockImplementation(() => {})
  vi.stubGlobal('fetch', vi.fn(async () => ({ ok: true, json: async () => ({ proposal: {
    steps: [{ text: steps[0], status: 'supported', evidence: 'HR sprawdza kompletność danych.' }, { text: steps[1], status: 'supported', evidence: 'biuro przygotowuje dokumenty.' }], roles: [], decisions: [{ text: 'Czy dane są kompletne?', status: 'assumption' }], questions: [],
    exceptions: [
      { text: 'Brak załącznika', status: 'assumption' },
      { text: 'Przykład do weryfikacji', status: 'assumption' },
    ],
  } }) })))
  const view = render(<App />)
  await user.click(screen.getByRole('button', { name: /Dodaj kroki samodzielnie/ }))
  await user.type(screen.getByLabelText(/Nazwa procesu/), 'Fikcyjny obieg dokumentów')
  await user.type(screen.getByLabelText(/Cel procesu/), 'Terminowe przygotowanie dokumentów')
  await user.type(screen.getByLabelText(/Co rozpoczyna proces/), 'Wpłynięcie zgłoszenia')
  await user.type(screen.getByLabelText(/Co kończy proces/), 'Przekazanie dokumentów')
  await user.click(screen.getByRole('button', { name: /Zapisz zakres i przejdź dalej/ }))
  await user.type(screen.getByLabelText('Tekst rozmowy'), transcript)
  await user.click(screen.getByRole('button', { name: 'Zapisz transkrypcję' }))
  await user.click(screen.getByRole('button', { name: 'Analizuj transkrypcję' }))
  expect(await screen.findByLabelText('Kroki — pozycja 1')).toHaveProperty('value', steps[0])
  await user.click(screen.getByRole('checkbox', { name: 'Sprawdzono treść — decyzje, pozycja 1' }))
  await user.click(screen.getByRole('checkbox', { name: 'Sprawdzono treść — wyjątki, pozycja 1' }))
  await user.click(screen.getByRole('button', { name: 'Zapisz propozycję' }))
  await user.click(screen.getByRole('checkbox', { name: 'Wybierz krok 1 do przeniesienia' }))
  await user.click(screen.getByRole('checkbox', { name: 'Wybierz krok 2 do przeniesienia' }))
  await user.click(screen.getByRole('button', { name: 'Przenieś wybrane kroki do AS-IS' }))
  const source = screen.getByLabelText('Od kroku')
  const target = screen.getByLabelText('Do kroku')
  await user.selectOptions(source, within(source).getByRole('option', { name: `2. ${steps[1]}` }))
  await user.selectOptions(target, within(target).getByRole('option', { name: `1. ${steps[0]}` }))
  await user.type(screen.getByLabelText('Kiedy następuje przejście?'), 'Brak danych')
  await user.click(screen.getByRole('button', { name: 'Dodaj połączenie' }))
  const question = screen.getByLabelText(`Pytanie decyzji — ${steps[1]}`)
  await user.type(question, 'Pytanie wpisane wcześniej')
  await user.selectOptions(screen.getByLabelText(`Sprawdzona decyzja z warsztatu — ${steps[1]}`), 'Czy dane są kompletne?')
  const insert = screen.getByRole('button', { name: `Wstaw pytanie z warsztatu — ${steps[1]}` })
  confirm.mockReturnValueOnce(false)
  await user.click(insert)
  expect(question.value).toBe('Pytanie wpisane wcześniej')
  await user.click(insert)
  expect(question.value).toBe('Czy dane są kompletne?')
  await user.type(screen.getByLabelText(`Kiedy kontynuować podstawową ścieżkę — ${steps[1]}`), 'Dane kompletne')
  await user.click(screen.getByRole('button', { name: `Zapisz decyzję BPMN — ${steps[1]}` }))
  await user.type(screen.getByLabelText(/Nazwa kroku/), 'Krok w formularzu')
  await user.click(screen.getByRole('button', { name: 'Zapisz proces AS-IS' }))
  expect(screen.getByText('Dokończ formularz kroku AS-IS przed zapisem procesu.')).toBeTruthy()
  await user.clear(screen.getByLabelText(/Nazwa kroku/))
  await user.click(screen.getByRole('button', { name: 'Zapisz proces AS-IS' }))
  await user.click(screen.getByRole('button', { name: /Nowy proces/ }))
  view.unmount()
  sessionStorage.setItem('architekt-procesow-screen-to-open', 'processes')
  const reopened = render(<App />)
  await user.click(screen.getByRole('button', { name: 'Otwórz proces' }))
  expect(screen.getByLabelText('Tekst rozmowy').value).toBe(transcript)
  expect(JSON.parse(localStorage.getItem('architekt-procesow:as-is')).steps.map((step) => step.name)).toEqual(steps)
  expect(screen.getByLabelText(`Pytanie decyzji — ${steps[1]}`).value).toBe('Czy dane są kompletne?')
  await user.click(screen.getByRole('button', { name: 'Przejdź do analizy' }))
  const exception = screen.getByLabelText('Sprawdzony wyjątek z warsztatu')
  expect(within(exception).queryByRole('option', { name: 'Przykład do weryfikacji' })).toBeNull()
  await user.selectOptions(exception, 'Brak załącznika')
  const name = screen.getByLabelText(/Nazwa problemu lub obserwacji/)
  await user.type(name, 'Robocze ustalenie')
  const insertException = screen.getByRole('button', { name: 'Wstaw wyjątek do formularza' })
  confirm.mockReturnValueOnce(false)
  await user.click(insertException)
  expect(name.value).toBe('Robocze ustalenie')
  await user.click(insertException)
  expect(name.value).toBe('Brak załącznika')
  expect(screen.getByLabelText(/Kategoria/).value).toBe('')
  await user.selectOptions(screen.getByLabelText(/Kategoria/), 'Ryzyko lub możliwość błędu')
  await user.click(screen.getByRole('button', { name: 'Dodaj ustalenie' }))
  await user.selectOptions(screen.getByLabelText(/Kategoria/), 'Wąskie gardło')
  await user.type(screen.getByLabelText(/Nazwa problemu lub obserwacji/), 'Brak terminu przekazania')
  await user.type(screen.getByLabelText('Wstępny pomysł usprawnienia'), 'Ustalić wspólny termin')
  await user.click(screen.getByRole('button', { name: 'Dodaj ustalenie' }))
  await user.click(screen.getByRole('button', { name: 'Zapisz analizę' }))
  await user.click(screen.getByRole('button', { name: 'Przejdź do TO-BE' }))
  await user.type(screen.getByLabelText(/Cel projektowanej zmiany/), 'Ustalić termin przekazania')
  const copyMap = screen.getByRole('button', { name: 'Skopiuj mapę BPMN z AS-IS' })
  await user.click(copyMap)
  expect(copyMap.disabled).toBe(true)
  expect(screen.getByLabelText(`Pytanie decyzji — ${steps[1]}`).value).toBe('Czy dane są kompletne?')
  await user.clear(screen.getByLabelText(`Pytanie decyzji — ${steps[1]}`))
  await user.type(screen.getByLabelText(`Pytanie decyzji — ${steps[1]}`), 'Czy dane TO-BE są kompletne?')
  await user.click(screen.getByRole('button', { name: `Zapisz decyzję BPMN — ${steps[1]}` }))
  await user.click(screen.getAllByRole('button', { name: 'Edytuj krok', exact: true })[0])
  const sourceOwner = screen.getByLabelText('Osoba lub rola odpowiedzialna')
  await user.clear(sourceOwner)
  await user.type(sourceOwner, 'Zespół kontroli')
  await user.click(screen.getByRole('button', { name: 'Zapisz zmiany', exact: true }))
  const included = within(screen.getByRole('region', { name: 'Ustalenia do uwzględnienia' }))
  const missingFinding = included.getByRole('checkbox', { name: /Brak załącznika/ }).closest('label')
  const linkedFinding = included.getByRole('checkbox', { name: /Brak terminu przekazania/ }).closest('label')
  expect(within(missingFinding).getByText('Brak powiązanego kroku TO-BE')).toBeTruthy()
  expect(within(linkedFinding).getByText('Brak powiązanego kroku TO-BE')).toBeTruthy()
  const stepName = screen.getByLabelText(/Nazwa kroku/)
  const link = screen.getByLabelText('Powiązane usprawnienie')
  const finding = within(link).getByRole('option', { name: 'Brak terminu przekazania' })
  await user.selectOptions(link, finding)
  await user.type(stepName, 'Ręcznie wpisana nazwa')
  const owner = screen.getByLabelText('Osoba lub rola odpowiedzialna')
  await user.type(owner, 'Zespół HR')
  const useIdea = screen.getByRole('button', { name: 'Użyj pomysłu jako nazwy kroku' })
  confirm.mockReturnValueOnce(false)
  await user.click(useIdea)
  expect(stepName.value).toBe('Ręcznie wpisana nazwa')
  await user.click(useIdea)
  expect(stepName.value).toBe('Ustalić wspólny termin')
  expect(owner.value).toBe('Zespół HR')
  const missingOption = within(link).getByRole('option', { name: 'Brak załącznika' })
  const additional = screen.getByText('Dodatkowe ustalenia', { exact: true })
  await user.click(additional)
  await user.click(within(additional.closest('details')).getByRole('checkbox', { name: 'Brak załącznika', exact: true }))
  await user.click(screen.getByRole('button', { name: 'Dodaj krok', exact: true }))
  expect(within(linkedFinding).getByText('Powiązane kroki TO-BE: Ustalić wspólny termin')).toBeTruthy()
  expect(within(linkedFinding).queryByText('Brak powiązanego kroku TO-BE')).toBeNull()
  expect(within(missingFinding).getByText('Powiązane kroki TO-BE: Ustalić wspólny termin')).toBeTruthy()
  expect(within(missingFinding).queryByText('Brak powiązanego kroku TO-BE')).toBeNull()
  await user.click(screen.getByRole('button', { name: 'Zapisz proces TO-BE' }))
  const asIs = JSON.parse(localStorage.getItem('architekt-procesow:as-is')).steps
  const toBe = JSON.parse(localStorage.getItem('architekt-procesow:to-be')).steps
  expect(toBe[1].extraConnections[0].targetId).toBe(toBe[0].id)
  expect(toBe[0].id).not.toBe(asIs[0].id)
  expect(toBe[0].sourceAsIsStepId).toBe(asIs[0].id)
  expect(asIs[1].bpmnDecision.question).toBe('Czy dane są kompletne?')
  expect(toBe[1].bpmnDecision.question).toBe('Czy dane TO-BE są kompletne?')
  expect(toBe[2]).toMatchObject({
    name: 'Ustalić wspólny termin', owner: 'Zespół HR',
    findingId: finding.value, additionalFindingIds: [missingOption.value],
  })
  await user.click(screen.getByRole('button', { name: 'Przejdź do raportu' }))
  await user.type(screen.getByLabelText(/Nazwa osoby, roli lub zespołu/), 'Koordynator HR')
  await user.click(screen.getByRole('button', { name: 'Dodaj interesariusza' }))
  for (const step of [...steps, 'Ustalić wspólny termin']) {
    await user.selectOptions(screen.getByLabelText(`${step}: Koordynator HR`), 'RA')
  }
  await user.click(screen.getByRole('button', { name: 'Zapisz raport' }))
  expect(screen.getByText('Raport procesu został zapisany')).toBeTruthy()
  reopened.unmount()
  render(<App />)
  expect(screen.getByText('Raport procesu został zapisany')).toBeTruthy()
  const report = screen.getByRole('heading', { name: 'Podsumuj proces i odpowiedzialności' }).closest('.report-workspace')
  for (const counter of within(report).getAllByText('Zmienione kroki', { exact: true })) {
    expect(counter.previousElementSibling.textContent).toBe('1')
  }
  const copiedStep = within(report).getAllByText(steps[0], { exact: true })
    .map((item) => item.closest('.report-steps li')).filter((item) => item?.querySelector('.step-type'))
  expect(copiedStep).toHaveLength(2)
  expect(copiedStep.every((item) => within(item).getByText('Zmieniony'))).toBe(true)
  expect(within(report).getAllByText('Brak terminu przekazania').length).toBeGreaterThan(0)
  expect(within(report).getAllByText('Ustalić termin przekazania').length).toBeGreaterThan(0)
  expect(within(report).getAllByText('Odpowiedzialność: nie określono → Zespół kontroli').length).toBeGreaterThan(0)
  const addedSteps = within(report).getAllByRole('heading', { name: 'Kroki TO-BE bez powiązania z AS-IS' })
  expect(within(addedSteps[0].closest('article')).getByText('Ustalić wspólny termin')).toBeTruthy()
  const gapHeadings = within(report).getAllByRole('heading', { name: 'Wybrane ustalenia bez powiązanego kroku TO-BE' })
  for (const heading of gapHeadings) {
    expect(within(heading.closest('article')).getByText('Każde wybrane ustalenie ma powiązany krok TO-BE')).toBeTruthy()
  }
  const reportedStep = within(report).getAllByText('Ustalić wspólny termin', { exact: true })
    .map((item) => item.closest('.report-steps li')).find(Boolean)
  expect(within(reportedStep).getByText('Brak załącznika')).toBeTruthy()
  expect(within(reportedStep).getByText('Brak terminu przekazania')).toBeTruthy()
  await user.click(screen.getByRole('button', { name: 'Eksportuj do PDF' }))
  await vi.waitFor(() => expect(print).toHaveBeenCalledOnce())
}, 20000)
