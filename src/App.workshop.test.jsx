  await user.click(screen.getByRole('button', { name: 'Zapisz proces AS-IS' }))
  expect(screen.getByText('Proces AS-IS został zapisany')).toBeTruthy()

  const currentId = localStorage.getItem('architekt-procesow:current-process-id')
  const names = JSON.parse(localStorage.getItem('architekt-procesow:as-is')).steps.map((step) => step.name)
  expect(names).toEqual(['Sprawdzenie danych', 'Przekazanie danych'])
  await user.click(screen.getByRole('button', { name: /Nowy proces/ }))
  const library = JSON.parse(localStorage.getItem('architekt-procesow:processes'))
  expect(library).toHaveLength(1)
  expect(library[0].sections.asIs).toBeTruthy()
  const savedId = library[0].id
  expect(savedId).toBeTruthy()
  if (currentId) expect(savedId).toBe(currentId)

  view.unmount()
  sessionStorage.setItem('architekt-procesow-screen-to-open', 'processes')
  render(<App />)
  await user.click(screen.getByRole('button', { name: 'Otwórz proces' }))
  const restored = screen.getByRole('heading', { name: 'Kroki procesu' }).closest('.steps-list-section')
  const restoredNames = [...restored.querySelectorAll('ol.steps-list li .step-details strong')].map((node) => node.textContent)
  expect(restoredNames).toEqual(names)
  expect(screen.getByLabelText('Tekst rozmowy').value).toBe('HR sprawdza dane, a następnie je przekazuje.')
  expect(screen.getByText('Proces AS-IS został zapisany')).toBeTruthy()
